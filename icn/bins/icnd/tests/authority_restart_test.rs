//! N1-R1: the real `icnd` binary rehydrates N1 authority state across restarts, and refuses to
//! start rather than run without it.
//!
//! # What this covers, and what it does not
//!
//! This is **daemon startup and recovery** coverage. Every fact here is written offline, through
//! [`AuthorityRegistry::ingest`], while the daemon is stopped and the test holds the data
//! directory's storage lock (decision D3). Nothing in `icnd` produces or consumes N1 facts yet, so
//! this suite cannot cover a production authority transition — a fact arriving at a running node
//! and changing a decision it serves. That needs a producer, which needs its own design and
//! security review.
//!
//! What the suite does observe is the daemon's own work: the receipt it writes is computed from
//! the state it rehydrated at startup (decision D2), and refusals are read from exit status, the
//! log, the gateway port and the files on disk.
//!
//! | | scenario |
//! |---|---|
//! | A | SIGKILL, restart: identical decisions |
//! | B | graceful stop, restart: identical decisions |
//! | C | a corrupt fact: no start, nothing listening, no receipt |
//! | D | an initialized node whose store is gone: no start, nothing recreated |
//! | E | an incomplete restore: refused before the store is opened |
//! | F | the N2-A gate audits a populated authority store and clears it |
//! | G | a fresh node initializes, records it, and reopens as the same instance |
//! | H | a start the N2-A gate refuses leaves no receipt from the previous start |
#![allow(clippy::unwrap_used, clippy::expect_used)]

use std::path::{Path, PathBuf};
use std::process::ExitStatus;
use std::time::{Duration, Instant};

use icn_core::authority_facts::AUTHORITY_FACT_PREFIX;
use icn_core::authority_registry::{
    init_record_path, receipt_path, AuthorityReceipt, AuthorityRegistry, Startup, ViewReceipt,
};
use icn_core::config::authority_fact_store_path;
use icn_identity::authority_log::{
    authorize_event, AuthorityStore, CapabilitySet, ContextNonce, ContinuityRoot, DeviceCapability,
    PrincipalKey, SignedAuthorityEvent,
};
use icn_store::{SledStore, Store};

const PASSPHRASE: &str = "test-only-not-a-real-credential";
const DEADLINE: Duration = Duration::from_secs(120);

fn icnd_bin() -> PathBuf {
    PathBuf::from(env!("CARGO_BIN_EXE_icnd"))
}

// ── N1 fixtures ─────────────────────────────────────────────────────────────────────────────────

fn root(seed: u8) -> ContinuityRoot {
    ContinuityRoot::new([seed; 32], ContextNonce::from_bytes([seed ^ 0xa5; 32]), 2)
}

/// A device principal that is not part of any subject's authority chain.
fn device(seed: u8) -> PrincipalKey {
    PrincipalKey::try_from_verifying_key(root(seed).authority_signing_key(0).verifying_key())
        .unwrap()
}

fn grant(
    signer: &ContinuityRoot,
    inception: &SignedAuthorityEvent,
    position: u64,
    prev: &SignedAuthorityEvent,
    dev: u8,
) -> SignedAuthorityEvent {
    authorize_event(
        &signer.authority_signing_key(0),
        inception.body.subject(),
        position,
        prev.body.event_id(),
        device(dev),
        CapabilitySet::new([DeviceCapability::Sign]),
        None,
    )
}

/// Subject 1: `Live` at frontier 2 with exactly device 110, plus an admitted grant for device 112
/// signed by subject 2's key that `derive` must ignore. Subject 2: `Halted` at position 1.
fn history() -> Vec<SignedAuthorityEvent> {
    let (r1, r2) = (root(1), root(2));
    let i1 = r1.incept().unwrap();
    let i2 = r2.incept().unwrap();
    let a1 = grant(&r1, &i1, 1, &i1, 110);
    let stranger = grant(&r2, &i1, 2, &a1, 112);
    let c1 = grant(&r2, &i2, 1, &i2, 120);
    let c2 = grant(&r2, &i2, 1, &i2, 121);
    vec![i1, a1, stranger, i2, c1, c2]
}

fn expected_receipt() -> AuthorityReceipt {
    let mut store = AuthorityStore::new();
    for event in history() {
        store.ingest(&event).unwrap();
    }
    AuthorityReceipt::of(&store, [0; 16], Startup::Rehydrated)
}

// ── a disposable node ───────────────────────────────────────────────────────────────────────────

struct Node {
    root: tempfile::TempDir,
    config: PathBuf,
    gateway_port: u16,
}

impl Node {
    /// `icnd --init` into a fresh directory, rebound to loopback. Generated by the daemon itself,
    /// so the only thing under test is what this suite changes.
    fn init(name: &str) -> Self {
        let root = tempfile::TempDir::new().unwrap();
        let gateway_port = free_tcp_port();
        let init = std::process::Command::new(icnd_bin())
            .args(["--init", "--node-name", name])
            .arg("--data-dir")
            .arg(root.path())
            .args(["--init-gateway-port", &gateway_port.to_string()])
            .args(["--init-gossip-port", &free_udp_port().to_string()])
            .env("ICN_KEYSTORE_PASSPHRASE", PASSPHRASE)
            .output()
            .unwrap();
        assert!(
            init.status.success(),
            "fixture: --init must succeed:\n{}{}",
            String::from_utf8_lossy(&init.stdout),
            String::from_utf8_lossy(&init.stderr)
        );
        let config = icn_core::config::config_file_path(root.path());
        let generated = std::fs::read_to_string(&config).unwrap();
        let loopback = generated.replace("0.0.0.0:", "127.0.0.1:");
        assert_ne!(
            loopback, generated,
            "fixture: the generated config binds 0.0.0.0"
        );
        std::fs::write(&config, loopback).unwrap();
        Node {
            root,
            config,
            gateway_port,
        }
    }

    fn dir(&self) -> &Path {
        self.root.path()
    }

    fn store(&self) -> PathBuf {
        authority_fact_store_path(self.dir())
    }

    /// D3: write facts through the reviewed interface, with the daemon stopped and this test
    /// holding the storage lock. Taking the lock would fail if a daemon were running.
    fn seed_offline(&self) {
        let lock = icn_core::DataDirLock::acquire(self.dir(), "offline test seeding").unwrap();
        let (mut registry, _) = AuthorityRegistry::open(self.dir(), &lock).unwrap();
        for event in history() {
            registry.ingest(&event).unwrap();
        }
    }

    /// Flip one byte of one persisted fact, offline and under the lock.
    fn corrupt_one_fact_offline(&self) {
        let _lock = icn_core::DataDirLock::acquire(self.dir(), "offline corruption").unwrap();
        let store = SledStore::open(self.store()).unwrap();
        let (key, mut value) = store
            .scan(AUTHORITY_FACT_PREFIX)
            .unwrap()
            .into_iter()
            .next()
            .unwrap();
        let last = value.len() - 1;
        value[last] ^= 0xff;
        store.put(&key, &value).unwrap();
        store.flush().unwrap();
    }

    /// Remove the receipt, so a restart has to write it again from what it rehydrated rather than
    /// leave the previous start's file in place.
    fn discard_receipt(&self) {
        std::fs::remove_file(receipt_path(self.dir())).unwrap();
    }

    fn receipt_bytes(&self) -> Vec<u8> {
        std::fs::read(receipt_path(self.dir())).unwrap()
    }

    fn receipt(&self) -> AuthorityReceipt {
        serde_json::from_slice(&self.receipt_bytes()).unwrap()
    }

    fn start(&self) -> Daemon {
        let mut daemon = Daemon::spawn(&self.config, self.dir());
        daemon.wait_until_running();
        daemon
    }

    /// Run a daemon that is expected to refuse, and return how it ended.
    fn run_expecting_refusal(&self) -> (ExitStatus, String) {
        let mut daemon = Daemon::spawn(&self.config, self.dir());
        let status = daemon.wait_for_exit().unwrap_or_else(|| {
            panic!(
                "the daemon was expected to refuse, but it was still running after {DEADLINE:?}:\n{}",
                daemon.log()
            )
        });
        (status, daemon.log())
    }

    fn gateway_listening(&self) -> bool {
        std::net::TcpStream::connect_timeout(
            &([127, 0, 0, 1], self.gateway_port).into(),
            Duration::from_millis(500),
        )
        .is_ok()
    }

    fn wait_for_gateway(&self) {
        let deadline = Instant::now() + DEADLINE;
        while Instant::now() < deadline {
            if self.gateway_listening() {
                return;
            }
            std::thread::sleep(Duration::from_millis(100));
        }
        panic!(
            "fixture: the gateway never listened on {}",
            self.gateway_port
        );
    }
}

fn assert_refused(node: &Node, status: ExitStatus, log: &str, expected: &str) {
    assert!(!status.success(), "the daemon must exit nonzero:\n{log}");
    assert!(
        status.code().is_some(),
        "it must exit, not be killed:\n{log}"
    );
    assert!(
        log.contains(expected),
        "the refusal must say {expected:?}:\n{log}"
    );
    assert!(
        !log.contains("Network actor running"),
        "no service may start after a refusal:\n{log}"
    );
    // The process has exited, so this cannot catch a listener it had; the log check above does
    // that. It does catch the port being held by anything a refusal left running.
    assert!(
        !node.gateway_listening(),
        "nothing may listen on the gateway port after a refusal"
    );
}

// ── A, B: restart ───────────────────────────────────────────────────────────────────────────────

/// The decisions in a receipt, checked against `derive` over an independently built store and
/// against the history's known shape — not only against the receipt code that produced them.
fn assert_decisions(receipt: &AuthorityReceipt) {
    let expected = expected_receipt();
    assert_eq!(receipt.subjects, expected.subjects);
    assert_eq!(receipt.decisions_digest, expected.decisions_digest);
    assert_eq!((receipt.body_count, receipt.witness_count), (6, 6));

    let views: Vec<&ViewReceipt> = receipt.subjects.iter().map(|s| &s.view).collect();
    let live = views
        .iter()
        .find_map(|v| match v {
            ViewReceipt::Live { state, frontier } => Some((state, *frontier)),
            _ => None,
        })
        .expect("one subject is Live");
    assert_eq!(live.1, 2);
    assert_eq!(
        live.0
            .devices
            .iter()
            .map(|d| d.device.clone())
            .collect::<Vec<_>>(),
        vec![hex::encode(device(110).as_bytes())],
        "exactly the authorized device; the stranger-signed grant is ignored"
    );
    assert!(
        views
            .iter()
            .any(|v| matches!(v, ViewReceipt::Halted { disputed_at: 1, .. })),
        "the other subject is Halted at position 1"
    );
}

#[test]
fn a_sigkilled_daemon_restarts_into_identical_authority_decisions() {
    let node = Node::init("n1r1-a");
    node.seed_offline();

    let mut daemon = node.start();
    node.wait_for_gateway();
    let before = node.receipt_bytes();
    assert_eq!(node.receipt().startup, Startup::Rehydrated);
    assert_decisions(&node.receipt());

    daemon.sigkill();
    node.discard_receipt();

    let _restarted = node.start();
    assert_eq!(
        node.receipt_bytes(),
        before,
        "the restarted daemon must derive byte-identical decisions"
    );
    assert_decisions(&node.receipt());
}

#[test]
fn a_gracefully_stopped_daemon_restarts_into_identical_authority_decisions() {
    let node = Node::init("n1r1-b");
    node.seed_offline();

    let mut daemon = node.start();
    let before = node.receipt_bytes();
    let status = daemon.sigterm();
    assert!(
        status.success(),
        "a graceful stop exits 0:\n{}",
        daemon.log()
    );
    node.discard_receipt();

    let _restarted = node.start();
    assert_eq!(node.receipt_bytes(), before);
    assert_decisions(&node.receipt());
}

// ── C, D, E: refusals ───────────────────────────────────────────────────────────────────────────

#[test]
fn a_corrupt_fact_stops_startup_before_anything_listens() {
    let node = Node::init("n1r1-c");
    node.seed_offline();
    assert!(
        receipt_path(node.dir()).exists(),
        "fixture: seeding wrote a receipt"
    );
    node.corrupt_one_fact_offline();

    let (status, log) = node.run_expecting_refusal();
    assert_refused(&node, status, &log, "did not rehydrate");
    assert!(
        log.contains(&node.store().display().to_string()),
        "names the store:\n{log}"
    );
    assert!(
        !receipt_path(node.dir()).exists(),
        "no receipt may describe a state the daemon did not start with"
    );
}

#[test]
fn an_initialized_node_whose_store_is_gone_refuses_and_recreates_nothing() {
    let node = Node::init("n1r1-d");
    let daemon = node.start();
    drop(daemon);
    assert!(node.store().is_dir() && init_record_path(node.dir()).is_file());

    std::fs::remove_dir_all(node.store()).unwrap();
    let (status, log) = node.run_expecting_refusal();
    assert_refused(&node, status, &log, "does not exist");
    assert!(
        !node.store().exists(),
        "the refusal must not create an empty store"
    );
}

#[test]
fn an_incomplete_restore_is_refused_before_the_authority_store_is_opened() {
    let node = Node::init("n1r1-e");
    std::fs::write(icn_core::restore_marker_path(node.dir()), b"").unwrap();

    let (status, log) = node.run_expecting_refusal();
    assert_refused(&node, status, &log, "did not finish");
    assert!(!node.store().exists(), "the store must not be created");
    assert!(!init_record_path(node.dir()).exists(), "nor the record");
}

// ── F: the N2-A gate ────────────────────────────────────────────────────────────────────────────

#[test]
fn the_n2a_gate_audits_a_populated_authority_store_and_clears_it() {
    let node = Node::init("n1r1-f");
    node.seed_offline();
    let _daemon = node.start();

    let gate: serde_json::Value = serde_json::from_slice(
        &std::fs::read(icn_store::n2a_startup_gate::receipt_path(node.dir())).unwrap(),
    )
    .unwrap();
    assert_eq!(gate["verdict"], "clear", "{gate:#}");
    let stores = gate["stores"].as_array().unwrap();
    let authority = stores
        .iter()
        .find(|s| {
            s["path"]
                .as_str()
                .is_some_and(|p| p.ends_with("store/authority"))
        })
        .unwrap_or_else(|| panic!("the gate must have audited store/authority:\n{gate:#}"));
    assert_eq!(authority["verdict"], "clear", "{authority:#}");
    assert!(
        authority["totalRows"].as_u64().unwrap() > history().len() as u64,
        "it audited the populated store (facts plus the instance row):\n{authority:#}"
    );
}

// ── G: a fresh node ─────────────────────────────────────────────────────────────────────────────

#[test]
fn a_fresh_node_initializes_records_it_and_reopens_as_the_same_instance() {
    let node = Node::init("n1r1-g");
    assert!(!node.store().exists() && !init_record_path(node.dir()).exists());

    let mut daemon = node.start();
    let first = node.receipt();
    assert_eq!(first.startup, Startup::Initialized);
    assert_eq!(first.body_count, 0);
    assert!(node.store().is_dir());
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt as _;
        let mode = std::fs::symlink_metadata(node.store())
            .unwrap()
            .permissions()
            .mode();
        assert_eq!(mode & 0o7777, 0o700, "the daemon's store is owner-only");
    }
    let record: serde_json::Value =
        serde_json::from_slice(&std::fs::read(init_record_path(node.dir())).unwrap()).unwrap();
    assert_eq!(record["instance"], first.instance.as_str());
    assert!(daemon.sigterm().success());

    let _restarted = node.start();
    let second = node.receipt();
    assert_eq!(second.startup, Startup::Rehydrated);
    assert_eq!(second.instance, first.instance);
}

// ── H: a receipt never outlives the start it describes ─────────────────────────────────────────

#[test]
fn a_start_refused_by_the_n2a_gate_leaves_no_receipt_from_the_previous_start() {
    let node = Node::init("n1r1-h");
    node.seed_offline();
    let mut daemon = node.start();
    assert!(daemon.sigterm().success());
    assert!(
        receipt_path(node.dir()).exists(),
        "fixture: a successful start wrote one"
    );

    // Make the gate refuse, before the registry is ever reached.
    std::fs::write(
        icn_store::n2a_startup_gate::receipt_path(node.dir()),
        b"not a gate receipt",
    )
    .unwrap();

    let (status, log) = node.run_expecting_refusal();
    assert_refused(&node, status, &log, "is unreadable");
    assert!(
        !log.contains("N1 authority registry: open"),
        "fixture: the refusal came before the registry:\n{log}"
    );
    assert!(
        !receipt_path(node.dir()).exists(),
        "the previous start's receipt must not survive to be read as this start's"
    );
}

// ── I: the import-incomplete marker (ADR-0089 §6, §7; refusal side only) ─────────────────────────

#[test]
fn an_unfinished_import_stops_startup_keeps_the_marker_and_loses_no_fact() {
    let node = Node::init("n1r1-i");
    node.seed_offline();
    let mut daemon = node.start();
    assert!(daemon.sigterm().success());
    assert!(
        receipt_path(node.dir()).exists(),
        "fixture: a successful start wrote one"
    );

    let marker = icn_core::import_marker::import_marker_path(node.dir());
    let record = format!(
        "icn-import-incomplete v1\nsegment-id {}\nsubject {}\nfact-count 3\n",
        "f320220a862f9e626da7edb0837e18198539ea27f04919d94441cc61897468ba",
        "a0068f2e8e052f31533edaac720f0911ef32aa24a4b056106b7bbb7002b4c04d",
    );
    std::fs::write(&marker, &record).unwrap();
    let record_before = std::fs::read(init_record_path(node.dir())).unwrap();

    // Twice: a repeated start is refused the same way and clears nothing.
    for attempt in 0..2 {
        let (status, log) = node.run_expecting_refusal();
        assert_refused(&node, status, &log, "offline N1 authority import");
        assert!(
            log.contains("not implemented yet"),
            "attempt {attempt}:\n{log}"
        );
        assert_eq!(
            std::fs::read(&marker).unwrap(),
            record.as_bytes(),
            "the marker is kept"
        );
        // The store's files are not compared byte for byte: the N2-A gate opens every sled root,
        // `store/authority` included, before the registry refuses (ADR-0089 §7 keeps that order),
        // and sled may write its own files on open. That no fact is lost is shown semantically by
        // the positive control below.
        assert_eq!(
            std::fs::read(init_record_path(node.dir())).unwrap(),
            record_before,
            "the record is untouched"
        );
        // Expected, not damage: the daemon discards the previous start's receipt as soon as it
        // holds the lock, before the registry refuses, so no stale receipt is read as this one's.
        assert!(!receipt_path(node.dir()).exists());
    }

    // The N2-A gate ran before the registry and did not take the marker for a store.
    let gate: serde_json::Value = serde_json::from_slice(
        &std::fs::read(icn_store::n2a_startup_gate::receipt_path(node.dir())).unwrap(),
    )
    .unwrap();
    assert_eq!(gate["verdict"], "clear", "{gate:#}");
    assert!(
        !gate.to_string().contains(".icn-import-incomplete"),
        "the marker is not a sled root:\n{gate:#}"
    );

    // Positive control (a test fixture, not an operator procedure): with the marker gone, the node
    // starts on exactly the facts it had, so the refused starts lost none.
    std::fs::remove_file(&marker).unwrap();
    let _daemon = node.start();
    assert_decisions(&node.receipt());
}

#[test]
fn an_unreadable_import_marker_stops_startup_too() {
    let node = Node::init("n1r1-j");
    node.seed_offline();
    let marker = icn_core::import_marker::import_marker_path(node.dir());
    std::fs::create_dir(&marker).unwrap();

    let (status, log) = node.run_expecting_refusal();
    assert_refused(&node, status, &log, "could not be read");
    assert!(marker.is_dir(), "the entry is kept");
}

// ── the daemon process ──────────────────────────────────────────────────────────────────────────

fn free_tcp_port() -> u16 {
    std::net::TcpListener::bind("127.0.0.1:0")
        .unwrap()
        .local_addr()
        .unwrap()
        .port()
}

fn free_udp_port() -> u16 {
    std::net::UdpSocket::bind("127.0.0.1:0")
        .unwrap()
        .local_addr()
        .unwrap()
        .port()
}

/// A daemon that is killed however the test leaves, so a failed assertion never strands a process
/// holding a lock.
struct Daemon {
    child: std::process::Child,
    log_path: PathBuf,
    _log_dir: tempfile::TempDir,
}

impl Daemon {
    fn spawn(config: &Path, data_dir: &Path) -> Self {
        let log_dir = tempfile::TempDir::new().unwrap();
        let log_path = log_dir.path().join("icnd.log");
        let log = std::fs::File::create(&log_path).unwrap();
        let child = std::process::Command::new(icnd_bin())
            .arg("--config")
            .arg(config)
            .arg("--data-dir")
            .arg(data_dir)
            .env("ICN_KEYSTORE_PASSPHRASE", PASSPHRASE)
            .stdin(std::process::Stdio::null())
            .stderr(log.try_clone().unwrap())
            .stdout(log)
            .spawn()
            .expect("the icnd binary must be runnable");
        Self {
            child,
            log_path,
            _log_dir: log_dir,
        }
    }

    fn log(&self) -> String {
        std::fs::read_to_string(&self.log_path).unwrap_or_default()
    }

    /// Block until the daemon is serving: "Network actor running" is logged after the registry
    /// opened and the services started.
    fn wait_until_running(&mut self) {
        let deadline = Instant::now() + DEADLINE;
        while Instant::now() < deadline {
            if self.log().contains("Network actor running") {
                return;
            }
            assert!(
                matches!(self.child.try_wait(), Ok(None)),
                "fixture: the daemon exited before it was serving:\n{}",
                self.log()
            );
            std::thread::sleep(Duration::from_millis(100));
        }
        panic!("fixture: the daemon never came up:\n{}", self.log());
    }

    fn wait_for_exit(&mut self) -> Option<ExitStatus> {
        let deadline = Instant::now() + DEADLINE;
        while Instant::now() < deadline {
            if let Some(status) = self.child.try_wait().unwrap() {
                return Some(status);
            }
            std::thread::sleep(Duration::from_millis(100));
        }
        None
    }

    /// SIGKILL: no destructor, no flush, no chance to close a store.
    fn sigkill(&mut self) {
        self.child.kill().unwrap();
        let status = self.child.wait().unwrap();
        assert_eq!(
            std::os::unix::process::ExitStatusExt::signal(&status),
            Some(libc::SIGKILL),
            "fixture: the daemon must have died of SIGKILL"
        );
    }

    fn sigterm(&mut self) -> ExitStatus {
        let pid = libc::pid_t::try_from(self.child.id()).unwrap();
        // SAFETY: `kill(2)` with a pid this test spawned and has not yet reaped.
        assert_eq!(unsafe { libc::kill(pid, libc::SIGTERM) }, 0);
        self.wait_for_exit()
            .unwrap_or_else(|| panic!("the daemon ignored SIGTERM:\n{}", self.log()))
    }
}

impl Drop for Daemon {
    fn drop(&mut self) {
        let _ = self.child.kill();
        let _ = self.child.wait();
    }
}
